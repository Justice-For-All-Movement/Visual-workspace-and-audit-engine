// Regenerates web/fixtures.js: real service-layer JSON captured from the E14 engine running against the fictional
// in-test engines on PostgreSQL. Usage: TEST_DATABASE_URL=… node scripts/build-web-fixtures.ts
import { writeFile } from 'node:fs/promises';
import pg from 'pg';
import * as kit from '../src/service-kit.ts';
import { createEngine, migrate } from '../src/engine/index.ts';
import { ADMIN, ALL_CAPS, buildWorld, ctxOf } from '../tests/engine-helpers.ts';

if (ADMIN === '') throw new Error('TEST_DATABASE_URL is required');
const strip = (ref: string): string => ref.replace(/@\d+$/, '');
await kit.withDisposableDatabase(pg, ADMIN, async (url, sql) => {
  await migrate(sql);
  const w = await buildWorld(sql, url);
  const engine = createEngine({ sql, ports: { engines: w.engines, controls: { E00: w.taskControls } }, config: { engineTimeoutMs: 300, controlTimeoutMs: 300 } });
  // The demo viewer is outside the sealed compartment and may not reassign tasks, so those states appear in the fixture.
  const viewer = (): kit.ServiceContext => ctxOf({ compartments: [], capabilities: ALL_CAPS.filter((c) => c !== 'orchestration:admin') });
  await engine.annotate(viewer(), { ref: 'E07:claim:c1', kind: 'review', body: 'Date in the ledger needs a second reader.' });
  const view = await engine.createView(viewer(), { name: 'Transfer story board', pins: [{ ref: 'E00:task:t1' }, { ref: 'E00:task:t2' }, { ref: 'E00:task:t3' }, { ref: 'E07:claim:c2' }], notes: 'Fictional demonstration board.' });
  await engine.applyUpstreamChange(ctxOf({ actor: { id: 'router', kind: 'service', roles: [] } }), { eventId: 'evt-demo-1', kind: 'claim_changed', refs: ['E07:claim:c2'], reason: 'Source scan was corrected' });

  const refs = ['E08:finding:f1', 'E07:claim:c1', 'E07:claim:c2', 'E05:evidence:ev1', 'E09:scene:s1', 'E00:task:t1', 'E00:task:t2', 'E00:task:t3', 'E06:derivative:d1', 'E11:permission:p1', 'E05:evidence:ev2', `E14:view:${view.id}`];
  const capture = async (fn: () => Promise<unknown>): Promise<unknown> => { try { return await fn(); } catch (e) { return { error: { code: (e as { code?: string }).code ?? 'error', message: (e as Error).message } }; } };
  const linked: Record<string, unknown> = {}, objects: Record<string, unknown> = {}, controls: Record<string, unknown> = {};
  for (const ref of refs) {
    linked[strip(ref)] = await capture(() => engine.inspectLinked(viewer(), ref, { depth: 2 }));
    objects[strip(ref)] = await capture(() => engine.inspectOne(viewer(), ref));
    controls[strip(ref)] = await capture(() => engine.listControls(viewer(), ref));
  }
  const search: Record<string, unknown> = {};
  for (const q of ['transfer', 'ledger', 'scene']) search[q] = await engine.searchAll(viewer(), { q });
  const overview = await engine.overview(viewer());
  const board = await engine.resolveView(viewer(), view.id);
  const tasks = await engine.inspectLinked(viewer(), 'E00:task:t1', { depth: 1, direction: 'downstream' });
  const failedTask = await engine.inspectLinked(viewer(), 'E00:task:t3', { depth: 0 });

  // Recorded control outcomes: each entry is what the engine really answered for that action on that object.
  const invocations: Record<string, Record<string, unknown>> = {};
  const record = async (ref: string, controlId: string, input: Record<string, string>, confirm = false): Promise<void> => {
    (invocations[ref] ??= {})[controlId] = await capture(() => engine.invokeControl(viewer(), ref, controlId, input, { confirm }));
  };
  await record('E00:task:t3', 'task.resume', {});
  await record('E00:task:t3', 'task.pause', {});
  await record('E00:task:t2', 'task.pause', {});
  await record('E00:task:t1', 'task.cancel', { reason: 'Duplicate of another task' }, true);
  await record('E07:claim:c1', 'workspace.request_correction', { body: 'The transfer date should read the 14th.' });
  await record('E07:claim:c1', 'workspace.export_audit', { format: 'csv' });
  const timeline = await engine.auditTimeline(viewer());

  const fixtures = { note: 'Fictional data captured from the E14 service layer running against in-test engines. Regenerate with scripts/build-web-fixtures.ts.', start: 'E08:finding:f1', overview, linked, objects, controls, search, board, tasks: { items: [...tasks.nodes, ...failedTask.nodes], edges: tasks.edges }, invocations, timeline };
  await writeFile(new URL('../web/fixtures.js', import.meta.url), `// Generated by scripts/build-web-fixtures.ts — do not edit by hand.\nexport default ${JSON.stringify(fixtures, null, 1)};\n`);
  process.stdout.write(`fixtures written: ${Object.keys(linked).length} linked views, ${timeline.records.length} audit records\n`);
});
